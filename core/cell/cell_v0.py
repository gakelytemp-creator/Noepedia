VERB_SUFFIX = ("ობდა","ებდა","ავდა","ობდნენ","ებდნენ","ობს","ებს","ავს","ამს",
               "ება","ობა","დნენ","ოდა","ოდნენ","ეთ!","ეო")
PREVERBS = ("გადმო","ჩამო","შემო","გამო","ამო","წამო","მი","მო","შე","გა","ჩა","წა","და","ა")

def load_mem():
    if os.path.exists(MEM_FILE):
        with open(MEM_FILE, encoding="utf-8") as f: return json.load(f)
    return {"learned": {}, "open_questions": {}, "fed_texts": []}

def save_mem(m):
    with open(MEM_FILE, "w", encoding="utf-8") as f:
        json.dump(m, f, ensure_ascii=False, indent=1)

def clean(w): return w.strip(".,!?…;:—-–()«»\"'“”*").lower()

def find_predicate(word, learned):
    for stem, v in learned.items():
        if len(stem) >= 3 and stem in word: return tuple(v)
    best = None
    for stem, v in LEX.items():
        if len(stem) >= 3 and stem in word:
            if best is None or len(stem) > best[0]: best = (len(stem), v)
    return best[1] if best else None

def looks_like_verb(word):
    if len(word) < 4: return False
    if any(word.endswith(s) for s in VERB_SUFFIX): return True
    if word.endswith(("ა","ო","ე")) and any(word.startswith(p) for p in PREVERBS) and len(word) >= 5:
        return True
    return False

def ask(question, qkey, mem):
    print("\n" + "─"*52)
    print("🐣 უჯრედი წყვეტს კვებას და გეკითხება:")
    print("   " + question)
    print("   [პასუხი: ფუძე=addr (მაგ. ეძებ=P078 ძებნა) · Enter = ვერ გეტყვი, OPEN დარჩეს]")
    try: ans = input("   შენ: ").strip()
    except EOFError: ans = ""
    if "=" in ans:
        stem, addr = ans.split("=", 1)
        mem["learned"][stem.strip()] = [addr.strip().split()[0], addr.strip()]
        mem["open_questions"].pop(qkey, None)
        print("   🐣 გავიგე! ჩავიწერე:", stem.strip(), "→", addr.strip())
        return True
    print("   🐣 კარგი, OPEN-ად ვიმახსოვრებ. კიდევ შემხვდება — ისევ გკითხავ.")
    return False

def main():
    if len(sys.argv) < 2:
        print("გამოყენება: python3 cell_v0.py ტექსტი.txt"); sys.exit(1)
    text = open(sys.argv[1], encoding="utf-8").read()
    mem = load_mem()
    sentences = [s.strip() for s in re.split(r"[.!?…\n]+", text) if s.strip()]
    born, digested, starved = set(), 0, 0
    unknown_counts = {}

    print(f"🐣 უჯრედი იღვიძებს. ლექსიკონში {len(set(a for a,_ in LEX.values()))} პრედიკატი"
          f" + ნასწავლი {len(mem['learned'])}. ღია კითხვა ძველიდან: {len(mem['open_questions'])}")
    print(f"   ვჭამ: {sys.argv[1]} ({len(sentences)} წინადადება)\n")

    for i, s in enumerate(sentences, 1):
        words = [clean(w) for w in s.split() if clean(w)]
        preds, unknowns = [], []
        for w in words:
            if w in STOP or len(w) < 3: continue
            p = find_predicate(w, mem["learned"])
            if p: preds.append(p)
            elif looks_like_verb(w): unknowns.append(w)
            else: born.add(w)                       # ობიექტი ჩუმად იბადება
        if preds: digested += 1
        for u in unknowns:
            key = u[:6]                             # უხეში ფუძე-გასაღები
            unknown_counts[key] = unknown_counts.get(key, 0) + 1
            if unknown_counts[key] == 2:            # კუტურიეს ზღურბლი
                q = f"„{u}" + "“ — ეს რა არის? მეორედ შემხვდა და ვერ ვჭამ."
                mem["open_questions"][key] = {"word": u, "where": s[:60], "type": "Q1"}
                ask(q, key, mem)
        if not preds and not unknowns and len(words) >= 4:
            starved += 1                            # წინადადება მოქმედების გარეშე

    print("\n" + "═"*52)
    print(f"🐣 ჭამა დასრულდა. მოვინელე: {digested}/{len(sentences)} წინადადება.")
    print(f"   ჩუმად დავბადე {len(born)} ობიექტი. მშიერი დავრჩი {starved} წინადადებაზე.")
    if mem["open_questions"]:
        print(f"   ღია კითხვა მრჩება {len(mem['open_questions'])}:")
        for k, q in list(mem["open_questions"].items())[:10]:
            print(f"     ❓ {q['word']}  (ვნახე: „{q['where']}…“)")
    else:
        print("   კითხვა აღარ მაქვს. მომეცი უფრო რთული ტექსტი!")
    mem["fed_texts"].append(sys.argv[1])
    save_mem(mem)
    print(f"   მეხსიერება შენახულია: {MEM_FILE}")

if __name__ == "__main__":
    main()
